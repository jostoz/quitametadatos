    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\r\n'
    f'<externalLink xmlns="{SS}"><externalBook>'
    '<sheetNames><sheetName val="Saldos"/></sheetNames></externalBook></externalLink>'
