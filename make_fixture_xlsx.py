"""Genera un .xlsx de prueba 'sucio': propiedades, propiedades personalizadas,
comentario con autor, lista de personas con cuenta, conexión a base de datos,
enlaces a otros libros, configuración de impresora, miniatura y hoja muy oculta.
Uso: make_fixture_xlsx.py salida.xlsx
"""
